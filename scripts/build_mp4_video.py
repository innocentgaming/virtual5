TEMP_DIR = os.path.abspath("temp_video_build")
os.makedirs(TEMP_DIR, exist_ok=True)

# Step 1: Generate High-Definition Speech Audio
print("--- Generating 4-Minute Studio 44.1kHz Spoken Audio Tracks ---")
scene_audio_files = []
scene_durations = []

for i, scene in enumerate(SCENES):
    raw_wav_path = os.path.join(TEMP_DIR, f"scene_raw_{i+1}.wav")
    padded_wav_path = os.path.join(TEMP_DIR, f"scene_{i+1}.wav")
    text = scene["narration"].replace('"', '\\"')
    target_dur = scene["target_dur"]
    
    ps_cmd = f'''
    Add-Type -AssemblyName System.Speech;
    $s = New-Object System.Speech.Synthesis.SpeechSynthesizer;
    
    $voices = $s.GetInstalledVoices() | Where-Object {{ $_.Enabled }};
    $zira = $voices | Where-Object {{ $_.VoiceInfo.Name -like "*Zira*" }} | Select-Object -First 1;
    $david = $voices | Where-Object {{ $_.VoiceInfo.Name -like "*David*" }} | Select-Object -First 1;
    if ($zira) {{ $s.SelectVoice($zira.VoiceInfo.Name) }}
    elseif ($david) {{ $s.SelectVoice($david.VoiceInfo.Name) }};
    
    $s.Rate = -1;
    $s.Volume = 100;
    
    $format = New-Object System.Speech.AudioFormat.SpeechAudioFormatInfo(44100, [System.Speech.AudioFormat.AudioBitsPerSample]::Sixteen, [System.Speech.AudioFormat.AudioChannel]::Stereo);
    $s.SetOutputToWaveFile('{raw_wav_path}', $format);
    $s.Speak("{text}");
    $s.Dispose();
    '''
    subprocess.run(["powershell", "-NoProfile", "-Command", ps_cmd], check=True)
    
    with wave.open(raw_wav_path, "r") as wf:
        frames = wf.getnframes()
        rate = wf.getframerate()
        raw_dur = frames / float(rate)
    
    final_scene_dur = max(raw_dur + 0.8, target_dur)
    scene_durations.append(final_scene_dur)
    
    pad_seconds = final_scene_dur - raw_dur
    subprocess.run([
        FFMPEG_EXE, "-y", "-i", raw_wav_path,
        "-af", f"apad=pad_dur={pad_seconds:.3f}",
        "-ar", "44100", padded_wav_path
    ], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    
    print(f"Scene {i+1}: Speech {raw_dur:.1f}s -> Padded Scene Duration: {final_scene_dur:.1f}s")
    scene_audio_files.append(padded_wav_path)

# Concatenate all audio tracks
raw_master_wav = os.path.join(TEMP_DIR, "raw_master_audio.wav")
concat_list = os.path.join(TEMP_DIR, "concat.txt")
with open(concat_list, "w") as f:
    for wav in scene_audio_files:
        f.write(f"file '{wav}'\n")

subprocess.run([
    FFMPEG_EXE, "-y", "-f", "concat", "-safe", "0", "-i", concat_list,
    "-c", "copy", raw_master_wav
], check=True)

# Step 2: Master Audio (Noise Filter + Speech Clarity Equalizer + Normalization)
master_wav = os.path.join(TEMP_DIR, "master_audio_enhanced.wav")
print("--- Mastering Voice Track (Equalizer + Normalization) ---")
subprocess.run([
    FFMPEG_EXE, "-y", "-i", raw_master_wav,
    "-af", "highpass=f=80,lowpass=f=12000,equalizer=f=3200:t=q:w=1.2:g=3.5,loudnorm=I=-16:TP=-1.5:LRA=9",
    "-ar", "44100", master_wav
], check=True)

# Step 3: Render Video Frames
output_mp4 = os.path.abspath("eventwise-ai-demo.mp4")
fps = 24
width, height = 1280, 720
total_duration = sum(scene_durations)
total_frames = int(total_duration * fps)

print(f"\nRendering {total_frames} video frames at {fps} FPS...")
print(f"Target Duration: {total_duration:.1f} seconds ({total_duration/60:.2f} minutes)\n")

ffmpeg_cmd = [
    FFMPEG_EXE, "-y",
    "-f", "rawvideo",
    "-vcodec", "rawvideo",
    "-s", f"{width}x{height}",
    "-pix_fmt", "rgb24",
    "-r", str(fps),
    "-i", "-",
    "-i", master_wav,
    "-c:v", "libx264",
    "-pix_fmt", "yuv420p",
    "-preset", "veryfast",
    "-crf", "20",
    "-c:a", "aac",
    "-b:a", "256k",
    "-ar", "44100",
    "-shortest",
    output_mp4
]

proc = subprocess.Popen(ffmpeg_cmd, stdin=subprocess.PIPE)

try:
    font_large = ImageFont.truetype("arialbd.ttf", 26)
    font_sub = ImageFont.truetype("arialbd.ttf", 15)
    font_body = ImageFont.truetype("arial.ttf", 17)
except:
    font_large = ImageFont.load_default()
    font_sub = ImageFont.load_default()
    font_body = ImageFont.load_default()

loaded_images = []
for s in SCENES:
    img_path = s["image"]
    if os.path.exists(img_path):
        base_img = Image.open(img_path).convert("RGB").resize((width, height), Image.Resampling.LANCZOS)
    else:
        base_img = Image.new("RGB", (width, height), color=(15, 23, 42))
    loaded_images.append(base_img)

frame_num = 0
for idx, scene in enumerate(SCENES):
    scene_dur = scene_durations[idx]
    scene_frame_count = int(scene_dur * fps)
    base_img = loaded_images[idx]
    
    title_text = scene["title"]
    sub_count_text = f"SCENE {idx+1} OF {len(SCENES)}"
    desc_text = scene["narration"]
    
    words = desc_text.split()
    lines = []
    curr = ""
    for w in words:
        if len(curr + " " + w) < 95:
            curr += " " + w if curr else w
        else:
            lines.append(curr)
            curr = w
    if curr:
        lines.append(curr)
    
    for f in range(scene_frame_count):
        frame = base_img.copy()
        draw = ImageDraw.Draw(frame, "RGBA")
        
        # Cinema Top Header Bar
        draw.rectangle([(0, 0), (width, 70)], fill=(9, 13, 22, 230))
        draw.text((40, 20), title_text, fill=(45, 212, 191), font=font_large)
        draw.text((1080, 26), sub_count_text, fill=(156, 163, 175), font=font_sub)
        
        # Bottom Subtitle Banner
        draw.rectangle([(40, 575), (width - 40, 695)], fill=(9, 13, 22, 245), outline=(45, 212, 191, 120), width=1)
        y_text = 590
        for l in lines[:4]:
            draw.text((64, y_text), l, fill=(255, 255, 255), font=font_body)
            y_text += 25
            
        # Overall Progress Bar
        global_progress = (frame_num / float(total_frames))
        bar_w = int(width * global_progress)
        draw.rectangle([(0, 714), (width, 720)], fill=(30, 41, 59))
        draw.rectangle([(0, 714), (bar_w, 720)], fill=(45, 212, 191))
        
        # Scene transition fade-in
        if f < 10:
            fade_alpha = int(255 * (1.0 - (f / 10.0)))
            overlay = Image.new("RGBA", (width, height), (9, 13, 22, fade_alpha))
            frame.paste(overlay, (0, 0), overlay)
            
        proc.stdin.write(frame.tobytes())
        frame_num += 1

proc.stdin.close()
proc.wait()

